const test = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const { createLaunchSafetyContext } = require('../../ecommerce-backend/backend/tests/helpers/launchSafetyHarness');
const Invoice = require('../../ecommerce-backend/backend/models/Invoice');
const { rejectManualPayment } = require('../../ecommerce-backend/backend/services/billing/paymentVerificationService');

test('billing renewal, cycle selection, history, rejection reason and partial API failure', { timeout: 120000 }, async t => {
    const origin = 'http://localhost:5188';
    process.env.CORS_ORIGINS = origin;
    process.env.ADMIN_APP_URL = origin;
    process.env.BILLING_BKASH_INSTRUCTIONS = 'Test merchant account: pay using your invoice reference';
    const cleanup = [];
    const ctx = await createLaunchSafetyContext({ after: action => cleanup.push(action) });
    const client = ctx.vendorAClient();
    const invoice = (await client.unsafePost('/api/admin/billing/invoices', { planName: 'Starter', billingCycle: 'yearly' })).body.data;
    const payment = (await client.unsafePost(`/api/admin/billing/invoices/${invoice.id}/submit-payment`, { amount: invoice.amount, provider: 'manual_bkash', transactionId: 'browser-rejected' })).body.data;
    await rejectManualPayment({ paymentId: payment.id, rejectionReason: 'Please check the transaction reference' });
    const base = (await Invoice.findById(invoice.id)).toObject();
    await Invoice.insertMany(Array.from({ length: 24 }, (_, i) => ({ ...base, _id: undefined, invoiceNumber: `history-${i}`, status: 'paid', createdAt: new Date(Date.now() + i + 1) })));
    const cwd = path.resolve(__dirname, '..');
    const server = spawn(process.execPath, [path.join(cwd, 'node_modules/vite/bin/vite.js'), '--host', 'localhost', '--port', '5188', '--strictPort'], { cwd, env: { ...process.env, VITE_API_URL: `${ctx.baseUrl.replace('127.0.0.1', 'localhost')}/api` }, stdio: 'ignore' });
    const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    t.after(async () => { await browser.close(); server.kill('SIGTERM'); for (const action of cleanup.reverse()) await action(); });
    for (let i = 0; i < 150; i++) { try { if ((await fetch(origin)).ok) break; } catch {} await new Promise(r => setTimeout(r, 100)); }
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: 'token', value: client.jar.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
    const page = await context.newPage();
    page.on('console', message => { if (message.type() === 'error') console.log('BROWSER', message.text()); });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/api/admin/billing/timeline*', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Test outage"}' }));
    await page.goto(`${origin}/dashboard/billing`);
    await page.getByRole('button', { name: 'Renew current plan' }).waitFor({ timeout: 10000 }).catch(async error => { console.log(await page.locator('body').innerText(), errors); throw error; });
    assert.equal(await page.getByRole('button', { name: 'Renew current plan' }).isEnabled(), true);
    await page.getByRole('button', { name: 'yearly', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Change billing cycle' }).isEnabled(), true);
    assert.match(await page.locator('body').innerText(), /Timeline could not load/);
    assert.match(await page.locator('body').innerText(), /Please check the transaction reference/);
    assert.match(await page.locator('body').innerText(), /Test merchant account/);
    assert.equal(await page.getByLabel('Amount', { exact: true }).inputValue(), String(invoice.amount));
    assert.equal(await page.getByLabel('Amount', { exact: true }).getAttribute('readonly'), '');
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    await page.getByText('Page 2 of 2 · 25 invoices').waitFor();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download receipt', exact: true }).first().click();
    assert.match((await download).suggestedFilename(), /\.txt$/);
    const created = page.waitForResponse(response => response.url().endsWith('/api/admin/billing/invoices') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Change billing cycle' }).click();
    assert.equal((await created).status(), 201);
    assert.deepEqual(errors, []);
});
