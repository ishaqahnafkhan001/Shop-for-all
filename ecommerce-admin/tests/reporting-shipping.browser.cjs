/* Disposable MONGO_URI_TEST required. Set PLAYWRIGHT_MODULE to the bundled Playwright package if needed. */
const test = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const ReturnRequest = require('../../ecommerce-backend/backend/models/ReturnRequest');
const FinancialFact = require('../../ecommerce-backend/backend/models/FinancialFact');
const { createLaunchSafetyContext, Order, Product } = require('../../ecommerce-backend/backend/tests/helpers/launchSafetyHarness');

const waitFor = async (check, message) => {
    for (let attempt = 0; attempt < 300; attempt++) {
        if (await check()) return;
        await new Promise(resolve => setTimeout(resolve, 100));
    }
    assert.fail(message);
};

test('report pages reconcile, handle failed requests, save merchant rates and quote actual checkout districts', { timeout: 180000 }, async t => {
    const adminOrigin = 'http://localhost:5187', storefrontOrigin = 'http://launchshopa.localhost:3197';
    process.env.CORS_ORIGINS = `${adminOrigin},${storefrontOrigin}`;
    process.env.ADMIN_APP_URL = adminOrigin;
    const cleanup = [];
    const ctx = await createLaunchSafetyContext({ after: action => cleanup.push(action) });
    const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
    const processes = [];
    const start = (cwd, script, args, env) => {
        const child = spawn(process.execPath, [script, ...args], { cwd, env: { ...process.env, ...env }, stdio: ['ignore', 'pipe', 'pipe'] });
        let log = '';
        child.stdout.on('data', chunk => { log += chunk; });
        child.stderr.on('data', chunk => { log += chunk; });
        processes.push(child);
        return () => { if (child.exitCode !== null) throw new Error(log); };
    };
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    t.after(async () => { await browser.close(); processes.forEach(child => child.kill('SIGTERM')); for (const action of cleanup.reverse()) await action(); });
    const api = `${ctx.baseUrl.replace('127.0.0.1', 'localhost')}/api`;
    const adminPath = path.resolve(__dirname, '..');
    const checkAdmin = start(adminPath, path.join(adminPath, 'node_modules/vite/bin/vite.js'), ['--host', 'localhost', '--port', '5187', '--strictPort'], { VITE_API_URL: api });
    await waitFor(async () => { checkAdmin(); try { return (await fetch(adminOrigin)).ok; } catch { return false; } }, 'Admin did not start');
    const { orderA } = ctx.data.orders;
    await Order.updateOne({ _id: orderA._id }, { $set: { status: 'Delivered', 'shipping.deliveredAt': new Date(Date.now() - 3600000) } });
    const context = await browser.newContext({ timezoneId: 'Asia/Dhaka', viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: 'token', value: ctx.vendorAClient().jar.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${adminOrigin}/dashboard`);
    await page.getByText('Net product sales', { exact: true }).first().waitFor();
    assert.match(await page.locator('body').innerText(), /1,200/);
    await page.getByLabel('Sales period').selectOption('7');
    await page.getByText('Net product sales', { exact: true }).first().waitFor();
    const failure = route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary test failure' }) });
    await page.route('**/api/admin/analytics?*', failure);
    await page.goto(`${adminOrigin}/dashboard/analytics`);
    await page.getByRole('button', { name: 'Retry', exact: true }).waitFor();
    assert.equal(await page.getByText('Net product sales', { exact: true }).count(), 0);
    await page.unroute('**/api/admin/analytics?*', failure);
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByText('Net product sales', { exact: true }).first().waitFor();
    assert.equal(await page.getByText('Not measured', { exact: true }).count(), 2);
    assert.match(await page.locator('body').innerText(), /BDT 1,200/);
    await page.getByLabel('Reporting period', { exact: true }).selectOption('custom');
    const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Dhaka' }).format(new Date());
    await page.getByLabel('From', { exact: true }).fill(today);
    await page.getByLabel('Through', { exact: true }).fill(today);
    await page.getByRole('button', { name: 'Apply dates' }).click();
    await page.getByRole('heading', { name: 'Compared with the previous period' }).waitFor();
    assert.match(page.url(), /range=custom/);
    await page.getByRole('button', { name: 'Save period', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Period saved on this device.' }).waitFor();
    await page.getByLabel('Reporting period', { exact: true }).selectOption('7');
    await page.getByRole('heading', { name: 'Compared with the previous period' }).waitFor();
    await page.getByRole('button', { name: 'Load saved period' }).click();
    await page.getByRole('heading', { name: 'Compared with the previous period' }).waitFor();
    assert.equal(await page.getByLabel('From', { exact: true }).inputValue(), today);
    const downloadPending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export CSV' }).click();
    const download = await downloadPending;
    const csv = fs.readFileSync(await download.path(), 'utf8');
    assert.match(csv, /"commerce-v2"/); assert.match(csv, /"summary"/);
    await page.getByText('Daily sales table', { exact: true }).click();
    await page.getByRole('columnheader', { name: 'Net sales (BDT)', exact: true }).waitFor();
    await page.goto(`${adminOrigin}/dashboard/growth`);
    await page.getByText(/Engagement ratios compare recorded product events/).waitFor();
    await page.getByText('Net product sales', { exact: true }).first().waitFor();
    await FinancialFact.createIndexes();
    const request = await ReturnRequest.create({ shop_id: orderA.shop_id, order_id: orderA._id, customer_id: orderA.customer,
        status: 'Approved', reason: 'Damaged return browser check', items: orderA.items.map(item => ({ ...item.toObject(), refundAmount: item.total })), refund: { amount: 1200 } });
    const initialStock = (await Product.findById(ctx.data.products.productA.product._id)).variants[0].stock;
    await page.goto(`${adminOrigin}/dashboard/returns`);
    await page.getByRole('button', { name: 'View', exact: true }).first().click();
    await page.getByLabel('Sellable units').fill('0');
    await page.getByLabel('Reason for units not restocked').fill('Damaged and cannot be sold');
    await page.getByRole('button', { name: 'Record receipt and restock' }).click();
    await page.getByText('Receipt recorded. Refund completion will not add stock again.', { exact: true }).waitFor();
    await page.getByLabel('Refund status', { exact: true }).selectOption('Refunded');
    await page.getByLabel('Total refund amount', { exact: true }).fill('1280');
    await page.getByLabel('Delivery refund (BDT)', { exact: true }).fill('80');
    await page.getByRole('button', { name: 'Save refund', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Refund details updated' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Save refund', exact: true }).isDisabled(), true);
    assert.equal((await Product.findById(ctx.data.products.productA.product._id)).variants[0].stock, initialStock);
    assert.equal((await ReturnRequest.findById(request._id)).refund.shippingAmount, 80);
    assert.equal(await FinancialFact.countDocuments({ order_id: orderA._id }), 3);
    await page.goto(`${adminOrigin}/dashboard/shipping`);
    await page.getByLabel('Base district').selectOption('Chattogram');
    await page.getByLabel('Inside Chattogram (৳)').fill('60');
    await page.getByLabel('Outside Chattogram (৳)').fill('150');
    await page.getByRole('button', { name: 'Save delivery charges' }).click();
    await page.getByRole('status').filter({ hasText: 'Delivery charges saved' }).waitFor();
    assert.equal((await ctx.vendorAClient().get('/api/admin/shipping/rates')).body.data.insideCharge, 60);
    const output = '/tmp/shop-reporting-browser'; fs.mkdirSync(output, { recursive: true });
    await page.screenshot({ path: `${output}/shipping-settings.png`, fullPage: true });
    const storefrontPath = path.resolve(__dirname, '../../ecommerce-storefront');
    const checkStorefront = start(storefrontPath, path.join(storefrontPath, 'node_modules/next/dist/bin/next'), ['dev', '--webpack', '-p', '3197'], { API_URL: api, NEXT_PUBLIC_API_URL: api, NEXT_PUBLIC_USE_DIRECT_API: 'false' });
    await waitFor(async () => { checkStorefront(); try { return (await fetch('http://localhost:3197')).status < 500; } catch { return false; } }, 'Storefront did not start');
    const storefront = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const item = ctx.data.products.productA;
    await storefront.addInitScript(({ product, variant }) => localStorage.setItem('shopforall_cart_launchshopa', JSON.stringify([{ ...product, variantId: variant._id, selectedVariant: variant, quantity: 1, finalPrice: 1200, sellingPrice: 1200, cartPrice: 1200 }])), JSON.parse(JSON.stringify(item)));
    const checkout = await storefront.newPage();
    checkout.on('pageerror', error => errors.push(error.message));
    await checkout.goto(`${storefrontOrigin}/checkout`);
    await checkout.getByLabel('Delivery district').waitFor();
    await checkout.getByLabel('Delivery district').selectOption('Chattogram');
    await checkout.getByText('Inside Chattogram district: ৳ 60', { exact: true }).last().waitFor();
    await checkout.getByLabel('Delivery district').selectOption('Dhaka');
    await checkout.getByText('Outside Chattogram district: ৳ 150', { exact: true }).last().waitFor();
    await checkout.screenshot({ path: `${output}/checkout-mobile.png`, fullPage: true });
    assert.deepEqual(errors, []);
});
