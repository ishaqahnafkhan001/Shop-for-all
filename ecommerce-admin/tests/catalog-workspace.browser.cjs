const test = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const { createLaunchSafetyContext } = require('../../ecommerce-backend/backend/tests/helpers/launchSafetyHarness');

test('catalog tabs, collection selection isolation, import preview, dialogs and mobile layout', { timeout: 120000 }, async t => {
    const origin = 'http://localhost:5187';
    process.env.CORS_ORIGINS = origin;
    process.env.ADMIN_APP_URL = origin;
    const cleanups = [];
    const ctx = await createLaunchSafetyContext({ after: callback => cleanups.push(callback) });
    const Collection = require('../../ecommerce-backend/backend/models/Collection');
    const own = ctx.data.products.productA.product;
    const collection = await Collection.create({ shop_id: own.shop_id, title: 'Test collection', slug: 'test-collection', productIds: [own._id] });
    const vite = spawn(process.execPath, [path.resolve(__dirname, '../node_modules/vite/bin/vite.js'), '--host', 'localhost', '--port', '5187', '--strictPort'], { cwd: path.resolve(__dirname, '..'), env: { ...process.env, VITE_API_URL: `${ctx.baseUrl.replace('127.0.0.1', 'localhost')}/api` }, stdio: 'ignore' });
    const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    t.after(async () => { await browser.close(); vite.kill(); for (const cleanup of cleanups.reverse()) await cleanup(); });
    for (let attempt = 0; attempt < 100; attempt++) {
        try { if ((await fetch(origin)).ok) break; } catch {}
        await new Promise(resolve => setTimeout(resolve, 100));
    }
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    await context.addCookies([{ name: 'token', value: ctx.vendorAClient().jar.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Lax' }]);
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${origin}/dashboard/catalog-tools`);
    await page.getByRole('heading', { name: 'Catalog', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Collections', exact: true }).click();
    await page.getByRole('button', { name: 'Edit Test collection', exact: true }).click();
    await page.getByRole('heading', { name: 'Collection members (1)', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Products & bulk edit', exact: true }).click();
    await page.getByRole('button', { name: 'Select page', exact: true }).click();
    await page.getByText('Move to category', { exact: true }).locator('..').locator('input').fill('Browser category');
    await page.getByRole('button', { name: 'Review and apply to 1 product', exact: true }).click();
    await page.getByRole('dialog', { name: 'Review bulk changes' }).waitFor();
    await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Collections', exact: true }).click();
    await page.getByRole('heading', { name: 'Collection members (1)', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Save collection', exact: true }).click();
    await page.getByText('Collection updated.', { exact: true }).waitFor();
    assert.equal((await Collection.findById(collection._id)).productIds.length, 1);
    await page.getByRole('button', { name: 'Import / Export', exact: true }).click();
    await page.getByLabel('Choose catalog CSV').setInputFiles({ name: 'catalog.csv', mimeType: 'text/csv', buffer: Buffer.from('title,sellingPrice,buyingPrice\nBrowser imported,100,50') });
    await page.getByRole('button', { name: 'Validate rows', exact: true }).click();
    await page.getByRole('button', { name: 'Apply 1 new products', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Categories', exact: true }).click();
    await page.getByRole('button', { name: /Edit .* search details/ }).first().click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.match(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), /search details/);
    await page.getByRole('button', { name: /Edit .* search details/ }).first().click();
    await page.getByLabel('Category name', { exact: true }).fill('Renamed category');
    await page.getByRole('button', { name: 'Save category details', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Products & bulk edit', exact: true }).click();
    await page.getByLabel('Category', { exact: true }).selectOption('Renamed category');
    await page.locator('#products').getByText('Renamed category', { exact: true }).last().waitFor();
    await page.screenshot({ path: '/tmp/catalog-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('button', { name: 'Select page', exact: true }).waitFor();
    await page.locator('#products').scrollIntoViewIfNeeded();
    await page.screenshot({ path: '/tmp/catalog-mobile.png', fullPage: true });
    assert.ok((await page.locator('#products').boundingBox()).width <= 390);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await context.route('**/api/admin/catalog/products?**', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Simulated failure' }) }));
    await page.reload();
    await page.getByRole('heading', { name: 'Products unavailable', exact: true }).waitFor();
    assert.deepEqual(errors, []);
});
