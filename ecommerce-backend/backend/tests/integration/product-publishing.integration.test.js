const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
const { Writable } = require('node:stream');
const sharp = require('sharp');
const { createLaunchSafetyContext, Product, InventoryLog } = require('../helpers/launchSafetyHarness');
const ProductSubmission = require('../../models/ProductSubmission');
const { cloudinary } = require('../../config/cloudinary');

const base = title => ({ title, description: 'A complete description for the publishing tests.', images: ['https://example.com/test.png'], pricing: { buyingPrice: 1, sellingPrice: 2 }, status: 'Draft', publicationStatus: 'draft', simpleStock: 4 });
const fingerprint = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const headers = (ctx, key, payload, identity = 'vendorA') => ({ 'X-Product-Submission': key, 'X-Product-Fingerprint': fingerprint(payload), 'X-Product-Actor': String(ctx.data.identities[identity].user._id), 'X-Product-Shop': String(ctx.data.identities[identity].user.shop_id) });
const waitFor = async predicate => { for (let i = 0; i < 100; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 10)); } assert.fail('Timed out'); };

test('publishing receipts replay a lost response, preserve drafts and initial stock, and isolate tenant and actor access', async t => {
    const ctx = await createLaunchSafetyContext(t);
    const client = ctx.vendorAClient();
    const key = randomUUID();
    const payload = base('Idempotent publishing');
    const h = headers(ctx, key, payload);
    const created = await client.unsafePost('/api/admin/products', payload, { headers: h });
    assert.equal(created.status, 201, created.text);
    const id = created.body.data._id;
    const replay = await client.unsafePost('/api/admin/products', payload, { headers: h });
    assert.equal(replay.status, 200, replay.text);
    assert.equal(replay.body.data._id, id);
    assert.equal(replay.body.replayed, true);
    assert.equal(await Product.countDocuments({ title: payload.title }), 1);
    assert.equal(await InventoryLog.countDocuments({ productId: id }), 1);
    const saved = await Product.findById(id);
    assert.equal(saved.publicationStatus, 'draft');
    assert.equal(saved.isActive, false);
    const status = await client.get(`/api/admin/product-submissions/${key}`, { headers: h });
    assert.equal(status.body.data.state, 'completed');
    assert.equal(status.body.data.productId, id);
    const foreign = await ctx.vendorBClient().get(`/api/admin/product-submissions/${key}`, { headers: headers(ctx, key, payload, 'vendorB') });
    assert.equal(foreign.body.data.state, 'not_found');
    const staff = await ctx.staffAClient().get(`/api/admin/product-submissions/${key}`, { headers: headers(ctx, key, payload, 'staffA') });
    assert.equal(staff.body.data.state, 'not_found');
    const switched = await ctx.vendorBClient().unsafePost('/api/admin/products', payload, { headers: h });
    assert.equal(switched.status, 403);
    assert.equal(switched.body.code, 'PRODUCT_SCOPE_CHANGED');
    const changed = { ...payload, title: 'Accidental replacement' };
    assert.equal((await client.unsafePost('/api/admin/products', changed, { headers: headers(ctx, key, changed) })).status, 409);
    await Product.deleteOne({ _id: id });
    const deletedReplay = await client.unsafePost('/api/admin/products', payload, { headers: h });
    assert.equal(deletedReplay.status, 200);
    assert.equal(deletedReplay.body.data.deleted, true);
    assert.equal(await Product.countDocuments({ title: payload.title }), 0);
});

test('rejected submissions restore and correct using the same stable identifier; authorization and CSRF cannot create receipts', async t => {
    const ctx = await createLaunchSafetyContext(t);
    const client = ctx.vendorAClient();
    const key = randomUUID();
    const invalid = { ...base('Correctable publishing'), pricing: { sellingPrice: -1 } };
    const rejected = await client.unsafePost('/api/admin/products', invalid, { headers: headers(ctx, key, invalid) });
    assert.equal(rejected.status, 400, rejected.text);
    await waitFor(async () => (await ProductSubmission.findOne({ key }))?.state === 'failed');
    assert.equal(await Product.countDocuments({ title: invalid.title }), 0);
    const good = base(invalid.title);
    const corrected = await client.unsafePost('/api/admin/products', good, { headers: headers(ctx, key, good) });
    assert.equal(corrected.status, 201, corrected.text);
    assert.equal(await Product.countDocuments({ title: invalid.title }), 1);
    assert.equal(await InventoryLog.countDocuments({ productId: corrected.body.data._id }), 1);
    const noCsrfKey = randomUUID();
    assert.equal((await client.post('/api/admin/products', good, { headers: headers(ctx, noCsrfKey, good) })).status, 403);
    assert.equal(await ProductSubmission.countDocuments({ key: noCsrfKey }), 0);
    const noSessionKey = randomUUID();
    assert.equal((await ctx.client().unsafePost('/api/admin/products', good, { headers: headers(ctx, noSessionKey, good) })).status, 401);
    assert.equal(await ProductSubmission.countDocuments({ key: noSessionKey }), 0);
});

test('concurrent duplicate multipart requests claim before upload, and replay does not upload again', async t => {
    const ctx = await createLaunchSafetyContext(t);
    const client = ctx.vendorAClient();
    const key = randomUUID();
    const payload = base('Multipart publishing');
    const h = headers(ctx, key, payload);
    const png = await sharp({ create: { width: 2, height: 2, channels: 3, background: '#fff' } }).png().toBuffer();
    const multipart = () => { const data = new FormData(); Object.entries(payload).filter(([key]) => key !== 'images').forEach(([key, value]) => data.append(key, typeof value === 'object' ? JSON.stringify(value) : String(value))); data.append('images', new Blob([png], { type: 'image/png' }), 'test.png'); return data; };
    const original = cloudinary.uploader.upload_stream;
    let uploaded = 0;
    let finish;
    cloudinary.uploader.upload_stream = (_options, callback) => new Writable({ write(_chunk, _encoding, done) { done(); }, final(done) { uploaded++; finish = () => { callback(null, { public_id: 'test/publishing', secure_url: 'https://example.com/publishing.png', resource_type: 'image' }); done(); }; } });
    t.after(() => { cloudinary.uploader.upload_stream = original; });
    const first = client.unsafePost('/api/admin/products', multipart(), { headers: h });
    await waitFor(() => uploaded === 1);
    const second = await client.unsafePost('/api/admin/products', multipart(), { headers: h });
    assert.equal(second.status, 409, second.text);
    assert.equal(second.body.code, 'SUBMISSION_PROCESSING');
    assert.equal(uploaded, 1);
    finish();
    const saved = await first;
    assert.equal(saved.status, 201, saved.text);
    assert.equal((await client.unsafePost('/api/admin/products', multipart(), { headers: h })).status, 200);
    assert.equal(uploaded, 1);
    assert.equal(await Product.countDocuments({ title: payload.title }), 1);
});

test('an expired admission can recover while fencing the previous owner; partial provider failures clean new assets', async t => {
    const ctx = await createLaunchSafetyContext(t);
    const client = ctx.vendorAClient();
    const payload = base('Expired admission publishing');
    const key = randomUUID();
    await ProductSubmission.create({ key, actor: ctx.data.identities.vendorA.user._id, shop_id: ctx.data.shops.shopA._id, fingerprint: fingerprint(payload), owner: 'old-worker', leaseUntil: new Date(Date.now() - 1000) });
    const recovered = await client.unsafePost('/api/admin/products', payload, { headers: headers(ctx, key, payload) });
    assert.equal(recovered.status, 201, recovered.text);
    const receipt = await ProductSubmission.findOne({ key });
    assert.notEqual(receipt.owner, 'old-worker');
    const { completeProductSubmission } = require('../../services/products/productSubmissionService');
    await assert.rejects(completeProductSubmission({ productSubmission: { _id: receipt._id, owner: 'old-worker' } }, recovered.body.data._id), /ownership changed/);

    const original = cloudinary.uploader.upload_stream;
    const destroy = cloudinary.uploader.destroy;
    const destroyed = [];
    let uploads = 0;
    cloudinary.uploader.upload_stream = (_options, callback) => new Writable({ write(_c, _e, done) { done(); }, final(done) { uploads++; uploads === 1 ? callback(null, { public_id: 'test/partial-publishing', secure_url: 'https://example.com/partial.png', resource_type: 'image' }) : callback(new Error('Provider temporarily unavailable')); done(); } });
    cloudinary.uploader.destroy = async id => { destroyed.push(id); return { result: 'ok' }; };
    t.after(() => { cloudinary.uploader.upload_stream = original; cloudinary.uploader.destroy = destroy; });
    const png = await sharp({ create: { width: 2, height: 2, channels: 3, background: '#fff' } }).png().toBuffer();
    const form = new FormData();
    const failed = base('Failed multipart publishing');
    Object.entries(failed).filter(([k]) => k !== 'images').forEach(([k, v]) => form.append(k, typeof v === 'object' ? JSON.stringify(v) : String(v)));
    form.append('images', new Blob([png], { type: 'image/png' }), 'one.png');
    form.append('images', new Blob([png], { type: 'image/png' }), 'two.png');
    const result = await client.unsafePost('/api/admin/products', form, { headers: headers(ctx, randomUUID(), failed) });
    assert.equal(result.status, 503, result.text);
    assert.equal(result.body.code, 'PRODUCT_UPLOAD_FAILED');
    assert(destroyed.includes('test/partial-publishing'));
    assert.equal(await Product.countDocuments({ title: failed.title }), 0);
});

test('the existing worker can clean interrupted upload intents without deleting committed or active media', async t => {
    const ctx = await createLaunchSafetyContext(t);
    const { cleanupProductSubmissionAssets, prepareSubmissionUpload } = require('../../services/products/productSubmissionService');
    const actor = ctx.data.identities.vendorA.user._id;
    const shop_id = ctx.data.shops.shopA._id;
    const leaseUntil = new Date(Date.now() - 1000);
    const cleanupAfter = new Date(Date.now() - 1000);
    const receipt = await ProductSubmission.create({ key: randomUUID(), actor, shop_id, fingerprint: fingerprint('interrupted'), owner: 'interrupted', leaseUntil, assets: [{ publicId: 'test/stale', resourceType: 'image', owner: 'interrupted', keep: false, cleanupAfter }] });
    const kept = await ProductSubmission.create({ key: randomUUID(), actor, shop_id, fingerprint: fingerprint('kept'), owner: 'committed', leaseUntil, state: 'completed', productId: ctx.data.products.productA.product._id, assets: [{ publicId: 'test/committed', resourceType: 'image', owner: 'committed', keep: true, cleanupAfter }] });
    const active = await ProductSubmission.create({ key: randomUUID(), actor, shop_id, fingerprint: fingerprint('active'), owner: 'active', leaseUntil: new Date(Date.now() + 60000), assets: [{ publicId: 'test/active', resourceType: 'image', owner: 'active', keep: false, cleanupAfter }] });
    const options = await prepareSubmissionUpload({ productSubmission: { _id: active._id, owner: 'active' } }, 'video');
    assert(options.public_id);
    assert.equal((await ProductSubmission.findById(active._id)).assets.length, 2);
    const destroy = cloudinary.uploader.destroy;
    const destroyed = [];
    cloudinary.uploader.destroy = async id => { destroyed.push(id); return { result: 'ok' }; };
    t.after(() => { cloudinary.uploader.destroy = destroy; });
    const result = await cleanupProductSubmissionAssets();
    assert.equal(result.cleaned, 1);
    assert.deepEqual(destroyed, ['test/stale']);
    assert.equal((await ProductSubmission.findById(receipt._id)).state, 'failed');
    assert.equal((await ProductSubmission.findById(receipt._id)).assets.length, 0);
    assert.equal((await ProductSubmission.findById(kept._id)).assets[0].keep, true);
    assert.equal((await ProductSubmission.findById(active._id)).state, 'processing');
    await assert.rejects(prepareSubmissionUpload({ productSubmission: { _id: receipt._id, owner: 'interrupted' } }, 'image'), /ownership changed/);
});
